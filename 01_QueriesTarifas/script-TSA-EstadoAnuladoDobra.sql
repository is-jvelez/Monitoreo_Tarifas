SELECT
        L.TarifaId,
        COUNT(D.ZohoCrmId)                                      AS DobraFilas,
        SUM(CASE WHEN D.Anulado = 1 THEN 1 ELSE 0 END)          AS DobraAnuladas,
        SUM(CASE WHEN D.Anulado = 0 THEN 1 ELSE 0 END)          AS DobraActivas,
        CASE
            WHEN COUNT(D.ZohoCrmId) = 0                                       THEN 'NO_EXISTE_EN_DOBRA'
            WHEN SUM(CASE WHEN D.Anulado = 1 THEN 1 ELSE 0 END) = COUNT(D.ZohoCrmId) THEN 'ANULADA_EN_DOBRA'
            WHEN SUM(CASE WHEN D.Anulado = 1 THEN 1 ELSE 0 END) = 0           THEN 'ACTIVA_EN_DOBRA'
            ELSE                                                                   'MIXTA_ACTIVA_Y_ANULADA'
        END                                                     AS EstadoTarifaDobra
FROM #Lista L
LEFT JOIN Cia.dbo.CLI_CLIENTES_TARIFAS_SERVICIOS_ADICIONALES D WITH (NOLOCK)
       ON D.ZohoCrmId = L.TarifaId
GROUP BY L.TarifaId
ORDER BY EstadoTarifaDobra, L.TarifaId;

-- 2) Resumen por estado (debe sumar 4750)
SELECT EstadoTarifaDobra, COUNT(*) AS Tarifas
FROM (
    SELECT L.TarifaId,
           CASE
               WHEN COUNT(D.ZohoCrmId) = 0                                       THEN 'NO_EXISTE_EN_DOBRA'
               WHEN SUM(CASE WHEN D.Anulado = 1 THEN 1 ELSE 0 END) = COUNT(D.ZohoCrmId) THEN 'ANULADA_EN_DOBRA'
               WHEN SUM(CASE WHEN D.Anulado = 1 THEN 1 ELSE 0 END) = 0           THEN 'ACTIVA_EN_DOBRA'
               ELSE                                                                   'MIXTA_ACTIVA_Y_ANULADA'
           END AS EstadoTarifaDobra
    FROM #Lista L
    LEFT JOIN Cia.dbo.CLI_CLIENTES_TARIFAS_SERVICIOS_ADICIONALES D WITH (NOLOCK)
           ON D.ZohoCrmId = L.TarifaId
    GROUP BY L.TarifaId
) X
GROUP BY EstadoTarifaDobra
ORDER BY EstadoTarifaDobra;

